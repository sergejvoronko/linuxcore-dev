// Workers static assets answer a slash-less page URL with a 307 (auto trailing
// slash). Google treats 307 as temporary and keeps the slash-less URL as a
// referrer, so every sitemap page gets an exact 301 rule in the built
// _redirects. Exact match means the slashed URL never matches itself, no loop.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const dir = 'dist/client';
const file = `${dir}/_redirects`;
const existing = readFileSync(file, 'utf8');
const sources = new Set(existing.split('\n').map((l) => l.trim().split(/\s+/)[0]).filter(Boolean));

const paths = readdirSync(dir)
  .filter((f) => /^sitemap-\d+\.xml$/.test(f))
  .flatMap((f) => [...readFileSync(`${dir}/${f}`, 'utf8').matchAll(/<loc>https?:\/\/[^/]+(\/[^<]*)<\/loc>/g)].map((m) => m[1]))
  .filter((p) => p.length > 1 && p.endsWith('/'));

const rules = [...new Set(paths)]
  .map((p) => p.slice(0, -1))
  .filter((src) => !sources.has(src))
  .map((src) => `${src} ${src}/ 301`);

if (!rules.length) throw new Error('slash-redirects: no sitemap URLs found in dist/client');
writeFileSync(file, `${existing.trimEnd()}\n\n# Generated by scripts/slash-redirects.mjs\n${rules.join('\n')}\n`);
console.log(`slash-redirects: ${rules.length} rules appended`);
